const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const { createTestDatabase } = require('./helpers/supabaseTestDb');
const { signPatientToken } = require('../middleware/auth');

test('Supabase supports staff login, clinic-linked patients, reminders and protected clinical data', async t => {
  await createTestDatabase(t);
  const previous = { JWT_SECRET: process.env.JWT_SECRET, ALLOWED_EMAIL_DOMAINS: process.env.ALLOWED_EMAIL_DOMAINS };
  process.env.JWT_SECRET = 'test-supabase-clinical-jwt-secret-at-least-32-characters';
  process.env.ALLOWED_EMAIL_DOMAINS = 'clinic.example';
  t.after(() => { for (const [key,value] of Object.entries(previous)) { if (value === undefined) delete process.env[key]; else process.env[key]=value; } });
  const app = express(); app.use(express.json());
  app.use('/auth', require('../routes/authRoutes'));
  app.use('/patients', require('../routes/patientAppRoutes'));
  app.use('/reminders', require('../routes/reminderRoutes'));
  app.use('/settings', require('../routes/settingsRoutes'));
  app.use((error,_req,res,_next) => res.status(error.status||500).json({error:error.message}));
  const server=app.listen(0,'127.0.0.1'); await new Promise(resolve=>server.once('listening',resolve));
  t.after(()=>{server.closeAllConnections();server.close()});
  const base=`http://127.0.0.1:${server.address().port}`;
  const call=async(path,method='GET',body,token)=>{const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:`Bearer ${token}`}:{})},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,body:await r.json()}};
  const registration=await call('/auth/register','POST',{name:'Clinician',email:'staff@clinic.example',password:'long-enough-password'});
  assert.equal(registration.status,201,JSON.stringify(registration.body));
  assert.equal(registration.body.user.passwordHash,undefined);
  const login=await call('/auth/login','POST',{email:'staff@clinic.example',password:'long-enough-password'});
  assert.equal(login.status,200,JSON.stringify(login.body));
  const staff=login.body.token;
  assert.equal((await call('/auth/me','GET',null,staff)).status,200);
  assert.equal((await call('/auth/login','POST',{email:'staff@clinic.example',password:'wrong-password'})).status,401);
  assert.equal((await call('/patients/P-1/profile','PUT',{name:'Patient One',email:'patient@example.com',mobile:'9000000091'},staff)).status,200);
  const patient=signPatientToken('P-1');
  const other=signPatientToken('P-2');
  assert.equal((await call('/patients/P-1/profile','GET',null,patient)).body.name,'Patient One');
  assert.equal((await call('/patients/P-1/profile','GET',null,other)).status,403);
  const created=await call('/reminders','POST',{patientId:'P-1',medicationName:'Test medication',times:['08:00'],pillsLeft:5},patient);
  assert.equal(created.status,201,JSON.stringify(created.body));
  assert.equal(created.body.active,true);assert.deepEqual(created.body.doseLog,[]);
  assert.match(created.body._id,/^[a-f0-9]{24}$/);
  const results=await Promise.all(Array.from({length:3},()=>call(`/reminders/${created.body._id}/doses`,'POST',{date:'2026-10-18',time:'08:00'},patient)));
  assert.ok(results.every(r=>r.status===200),JSON.stringify(results));
  const reminders=await call('/reminders/P-1','GET',null,patient);
  assert.equal(reminders.body.length,1);assert.equal(reminders.body[0].doseLog.length,1);assert.equal(reminders.body[0].pillsLeft,4);
  assert.equal((await call(`/reminders/${created.body._id}`,'DELETE',null,other)).status,403);
  assert.equal((await call(`/reminders/${created.body._id}`,'DELETE',null,patient)).status,200);
});
